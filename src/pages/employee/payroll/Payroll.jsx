import { useState } from "react";
import {
  Box,
  Typography,
  Paper,
  Button,
  TextField,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Chip,
  Grid,
  MenuItem,
} from "@mui/material";

import {
  Download,
  AccountBalanceWallet,
  Payments,
  People,
  ReceiptLong,
} from "@mui/icons-material";

const initialPayrollData = [
  {
    id: "PAY001",
    employeeId: "EMP001",
    employeeName: "Rahul Sharma",
    department: "IT",
    basicSalary: 30000,
    allowances: 10000,
    deductions: 3000,
    netSalary: 37000,
    status: "Paid",
  },
  {
    id: "PAY002",
    employeeId: "EMP002",
    employeeName: "Priya Verma",
    department: "HR",
    basicSalary: 25000,
    allowances: 8000,
    deductions: 2500,
    netSalary: 30500,
    status: "Pending",
  },
  {
    id: "PAY003",
    employeeId: "EMP003",
    employeeName: "Amit Kumar",
    department: "Finance",
    basicSalary: 35000,
    allowances: 12000,
    deductions: 4000,
    netSalary: 43000,
    status: "Paid",
  },
];

const Payroll = () => {
  const [payrollData, setPayrollData] = useState(initialPayrollData);
  const [month, setMonth] = useState("November");
  const [year, setYear] = useState("2026");
  const [search, setSearch] = useState("");

  const formatCurrency = (amount) =>
    new Intl.NumberFormat("en-IN", {
      style: "currency",
      currency: "INR",
      maximumFractionDigits: 0,
    }).format(amount);

  const filteredData = payrollData.filter(
    (item) =>
      item.employeeName.toLowerCase().includes(search.toLowerCase()) ||
      item.employeeId.toLowerCase().includes(search.toLowerCase()),
  );

  const totalSalary = payrollData.reduce(
    (total, item) => total + item.netSalary,
    0,
  );

  const paidSalary = payrollData
    .filter((item) => item.status === "Paid")
    .reduce((total, item) => total + item.netSalary, 0);

  const pendingCount = payrollData.filter(
    (item) => item.status === "Pending",
  ).length;

  const downloadPayslip = (employee) => {
    const payslipContent = `
EMPLOYEE PAYSLIP

Employee Name: ${employee.employeeName}
Employee ID: ${employee.employeeId}
Department: ${employee.department}

Basic Salary: ${formatCurrency(employee.basicSalary)}
Allowances: ${formatCurrency(employee.allowances)}
Deductions: ${formatCurrency(employee.deductions)}

Net Salary: ${formatCurrency(employee.netSalary)}

Payroll Month: ${month} ${year}
Payment Status: ${employee.status}

Note: This is a demo payslip generated by the frontend.
    `;

    const blob = new Blob([payslipContent], {
      type: "text/plain",
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = url;
    link.download = `${employee.employeeId}-payslip.txt`;

    link.click();
    URL.revokeObjectURL(url);
  };

  const markAsPaid = (id) => {
    setPayrollData((prev) =>
      prev.map((item) => (item.id === id ? { ...item, status: "Paid" } : item)),
    );
  };

  return (
    <Box>
      <Box mb={3}>
        <Typography variant="h5" fontWeight={700}>
          Payroll Management
        </Typography>

        <Typography color="text.secondary">
          Manage employee salaries and payroll records
        </Typography>
      </Box>

      <Grid container spacing={2} sx={{ mb: 3 }}>
        {[
          {
            label: "Total Payroll",
            value: formatCurrency(totalSalary),
            icon: <AccountBalanceWallet />,
          },
          {
            label: "Paid Amount",
            value: formatCurrency(paidSalary),
            icon: <Payments />,
          },
          {
            label: "Employees",
            value: payrollData.length,
            icon: <People />,
          },
          {
            label: "Pending Payments",
            value: pendingCount,
            icon: <ReceiptLong />,
          },
        ].map((item) => (
          <Grid item xs={12} sm={6} md={3} key={item.label}>
            <Paper sx={{ p: 2.5, borderRadius: 3 }}>
              <Box display="flex" justifyContent="space-between">
                <Box>
                  <Typography color="text.secondary">{item.label}</Typography>

                  <Typography variant="h5" fontWeight={700} mt={1}>
                    {item.value}
                  </Typography>
                </Box>

                <Box color="primary.main">{item.icon}</Box>
              </Box>
            </Paper>
          </Grid>
        ))}
      </Grid>

      <Paper sx={{ p: 2, borderRadius: 3 }}>
        <Box
          display="flex"
          flexWrap="wrap"
          justifyContent="space-between"
          gap={2}
          mb={3}
        >
          <Box display="flex" gap={2} flexWrap="wrap">
            <TextField
              select
              size="small"
              label="Month"
              value={month}
              onChange={(e) => setMonth(e.target.value)}
              sx={{ minWidth: 140 }}
            >
              {[
                "January",
                "February",
                "March",
                "April",
                "May",
                "June",
                "July",
                "August",
                "September",
                "October",
                "November",
                "December",
              ].map((item) => (
                <MenuItem key={item} value={item}>
                  {item}
                </MenuItem>
              ))}
            </TextField>

            <TextField
              select
              size="small"
              label="Year"
              value={year}
              onChange={(e) => setYear(e.target.value)}
              sx={{ minWidth: 110 }}
            >
              <MenuItem value="2026">2026</MenuItem>
              <MenuItem value="2027">2027</MenuItem>
            </TextField>
          </Box>

          <TextField
            size="small"
            placeholder="Search employee..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
          />
        </Box>

        <TableContainer>
          <Table>
            <TableHead>
              <TableRow>
                <TableCell>Employee</TableCell>
                <TableCell>Department</TableCell>
                <TableCell>Basic Salary</TableCell>
                <TableCell>Allowances</TableCell>
                <TableCell>Deductions</TableCell>
                <TableCell>Net Salary</TableCell>
                <TableCell>Status</TableCell>
                <TableCell>Action</TableCell>
              </TableRow>
            </TableHead>

            <TableBody>
              {filteredData.map((item) => (
                <TableRow key={item.id} hover>
                  <TableCell>
                    <Typography fontWeight={600}>
                      {item.employeeName}
                    </Typography>
                    <Typography variant="caption" color="text.secondary">
                      {item.employeeId}
                    </Typography>
                  </TableCell>

                  <TableCell>{item.department}</TableCell>
                  <TableCell>{formatCurrency(item.basicSalary)}</TableCell>
                  <TableCell>{formatCurrency(item.allowances)}</TableCell>
                  <TableCell>{formatCurrency(item.deductions)}</TableCell>

                  <TableCell>
                    <Typography fontWeight={700}>
                      {formatCurrency(item.netSalary)}
                    </Typography>
                  </TableCell>

                  <TableCell>
                    <Chip
                      label={item.status}
                      color={item.status === "Paid" ? "success" : "warning"}
                      size="small"
                    />
                  </TableCell>

                  <TableCell>
                    <Box display="flex" gap={1}>
                      <Button
                        size="small"
                        onClick={() => downloadPayslip(item)}
                        startIcon={<Download />}
                      >
                        Slip
                      </Button>

                      {item.status === "Pending" && (
                        <Button
                          size="small"
                          color="success"
                          onClick={() => markAsPaid(item.id)}
                        >
                          Mark Paid
                        </Button>
                      )}
                    </Box>
                  </TableCell>
                </TableRow>
              ))}

              {filteredData.length === 0 && (
                <TableRow>
                  <TableCell colSpan={8} align="center">
                    No payroll records found.
                  </TableCell>
                </TableRow>
              )}
            </TableBody>
          </Table>
        </TableContainer>
      </Paper>
    </Box>
  );
};

export default Payroll;
